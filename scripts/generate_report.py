#!/usr/bin/env python3
"""Build an executive CSPM report (HTML + JSON summary) from a findings file.

Standard library only. Input is either this repository's findings.json format
or a Prowler JSON-OCSF export (one object per finding, status_code FAIL).
"""
from __future__ import annotations

import argparse
import html
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

SEVERITY_WEIGHT = {"critical": 10, "high": 7, "medium": 4, "low": 1, "informational": 0}
SEVERITY_ORDER = ["critical", "high", "medium", "low", "informational"]


def load_findings(path: Path) -> tuple[dict, list[dict]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, dict) and "findings" in data:
        return data.get("assessment", {}), data["findings"]
    if isinstance(data, list):  # Prowler JSON-OCSF
        findings = []
        for i, item in enumerate(d for d in data if d.get("status_code") == "FAIL"):
            findings.append({
                "id": f"P{i + 1:03d}",
                "severity": str(item.get("severity", "low")).lower(),
                "service": item.get("resources", [{}])[0].get("group", {}).get("name", "unknown"),
                "title": item.get("finding_info", {}).get("title", item.get("message", "")),
                "check": item.get("metadata", {}).get("event_code", ""),
                "remediation": item.get("remediation", {}).get("desc", ""),
            })
        return {"data_origin": "prowler-ocsf"}, findings
    raise ValueError("Unrecognized findings format")


def risk_score(findings: list[dict]) -> float:
    """Weighted severity as a percentage of the worst case (every finding critical)."""
    if not findings:
        return 0.0
    total = sum(SEVERITY_WEIGHT.get(f["severity"], 0) for f in findings)
    return round(100 * total / (len(findings) * SEVERITY_WEIGHT["critical"]), 1)


def summarize(findings: list[dict]) -> dict:
    counts = Counter(f["severity"] for f in findings)
    by_service = Counter(f["service"] for f in findings)
    return {
        "total": len(findings),
        "risk_score": risk_score(findings),
        "by_severity": {s: counts.get(s, 0) for s in SEVERITY_ORDER if counts.get(s)},
        "by_service": dict(by_service.most_common()),
    }


def render_html(meta: dict, findings: list[dict], summary: dict, generated: str) -> str:
    rows = "\n".join(
        f"<tr><td>{html.escape(f['id'])}</td><td class='sev {html.escape(f['severity'])}'>{html.escape(f['severity'].upper())}</td>"
        f"<td>{html.escape(f['service'])}</td><td>{html.escape(f['title'])}</td><td>{html.escape(f['remediation'])}</td></tr>"
        for f in sorted(findings, key=lambda f: (SEVERITY_ORDER.index(f["severity"]), f["id"]))
    )
    tiles = "".join(
        f"<div class='tile'><b>{n}</b><span>{s.title()}</span></div>" for s, n in summary["by_severity"].items()
    )
    origin = html.escape(meta.get("data_origin", "unknown"))
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>CSPM Assessment Report</title><style>
body{{font:15px/1.5 system-ui,sans-serif;margin:0;padding:24px;color:#18202a;background:#f6f7f9}}
main{{max-width:1000px;margin:auto}} h1{{margin:0 0 4px}} .meta{{color:#5a6472}}
.note{{background:#fff4d6;border:1px solid #e8c766;padding:10px 12px;border-radius:8px;margin:16px 0}}
.tiles{{display:flex;gap:10px;flex-wrap:wrap;margin:16px 0}} .tile{{background:#fff;border:1px solid #dde1e6;border-radius:8px;padding:10px 14px;min-width:110px}}
.tile b{{display:block;font-size:1.6rem}} table{{width:100%;border-collapse:collapse;background:#fff}}
th,td{{text-align:left;padding:8px;border-bottom:1px solid #e6e9ed;vertical-align:top}}
.sev{{font-weight:700}} .critical{{color:#b3261e}} .high{{color:#c2571a}} .medium{{color:#8a6d00}} .low{{color:#3b6b3b}}
</style></head><body><main>
<h1>Cloud Security Posture Assessment</h1>
<div class="meta">Account: {html.escape(meta.get('account_label', 'n/a'))} · Region: {html.escape(meta.get('region', 'n/a'))} · Generated: {generated}</div>
<div class="note">Data origin: <b>{origin}</b>. {html.escape(meta.get('note', ''))}</div>
<p><b>Executive summary.</b> {summary['total']} findings, weighted risk score <b>{summary['risk_score']}</b> / 100.
Remediate critical items first: public storage, wildcard IAM permissions and internet-exposed SSH.</p>
<div class="tiles"><div class="tile"><b>{summary['risk_score']}</b><span>Risk score</span></div>{tiles}</div>
<table><thead><tr><th>ID</th><th>Severity</th><th>Service</th><th>Finding</th><th>Remediation</th></tr></thead><tbody>
{rows}
</tbody></table>
<p class="meta">Generated by scripts/generate_report.py · Risk score = Σ severity weight ÷ (findings × 10) × 100, weights critical 10 · high 7 · medium 4 · low 1.</p>
</main></body></html>"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("findings", type=Path)
    ap.add_argument("--out", type=Path, default=Path("reports"))
    ap.add_argument("--generated", default=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    args = ap.parse_args()
    meta, findings = load_findings(args.findings)
    summary = summarize(findings)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "assessment-report.html").write_text(render_html(meta, findings, summary, args.generated), encoding="utf-8")
    (args.out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
